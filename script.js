/* ===== Helpers ===== */
const SUPPORTED = ["nl", "fr", "en"];

function escapeHtml(str) {
  return str.replace(/[&<>"']/g, (c) => (
    { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]
  ));
}

function renderReviews(lang) {
  const grid = document.getElementById("reviews-grid");
  if (!grid) return;
  grid.innerHTML = REVIEWS.map((r) => `
    <figure class="review-card">
      <div class="review-stars" aria-hidden="true">&ldquo;</div>
      <blockquote class="review-text">${escapeHtml(r.text[lang])}</blockquote>
      <figcaption>
        <span class="review-author">${escapeHtml(r.author)}</span><br />
        <span class="review-meta">${escapeHtml(r.meta[lang])}</span>
      </figcaption>
    </figure>
  `).join("");
}

function applyLanguage(lang) {
  if (!SUPPORTED.includes(lang)) lang = "nl";
  const dict = I18N[lang];

  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });

  const toggle = document.querySelector(".nav-toggle");
  if (toggle) {
    const open = toggle.getAttribute("aria-expanded") === "true";
    toggle.setAttribute("aria-label", open ? dict.nav_close : dict.nav_open);
  }

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.setAttribute("aria-pressed", btn.dataset.lang === lang ? "true" : "false");
  });

  renderReviews(lang);

  try { localStorage.setItem("hlb-lang", lang); } catch (e) {}
}

/* ===== Init ===== */
document.addEventListener("DOMContentLoaded", () => {
  // Year
  const yearEl = document.getElementById("year");
  if (yearEl) yearEl.textContent = new Date().getFullYear();

  // Language: saved preference, else browser, else Dutch
  let initial = "nl";
  try {
    const saved = localStorage.getItem("hlb-lang");
    if (saved && SUPPORTED.includes(saved)) {
      initial = saved;
    } else {
      const nav = (navigator.language || "nl").slice(0, 2).toLowerCase();
      if (SUPPORTED.includes(nav)) initial = nav;
    }
  } catch (e) {}
  applyLanguage(initial);

  // Language buttons
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
  });

  // Mobile nav
  const toggle = document.querySelector(".nav-toggle");
  const menu = document.getElementById("nav-menu");
  const closeMenu = () => {
    if (!menu) return;
    menu.classList.remove("is-open");
    toggle.setAttribute("aria-expanded", "false");
    const dict = I18N[document.documentElement.lang] || I18N.nl;
    toggle.setAttribute("aria-label", dict.nav_open);
  };

  if (toggle && menu) {
    toggle.addEventListener("click", () => {
      const open = menu.classList.toggle("is-open");
      toggle.setAttribute("aria-expanded", open ? "true" : "false");
      const dict = I18N[document.documentElement.lang] || I18N.nl;
      toggle.setAttribute("aria-label", open ? dict.nav_close : dict.nav_open);
    });

    // Close after clicking a navigation link (but not language buttons)
    menu.querySelectorAll("a").forEach((link) => {
      link.addEventListener("click", closeMenu);
    });

    // Close on Escape
    document.addEventListener("keydown", (e) => {
      if (e.key === "Escape") closeMenu();
    });
  }
});
